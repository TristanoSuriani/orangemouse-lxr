"""Dexed's built-in DX7 cartridges as a C table, for engines/dexed/.

    tools/dexed_carts.py <builtin_pgm.zip> <out.c>

Each cartridge is a 32-voice bulk dump (4104 bytes: a 6-byte header, 32
packed voices of 128 bytes, a checksum and F7). The build runs this from
third_party/dexed/assets/builtin_pgm.zip (third_party/fetch.sh), so the
cartridges are not committed here.
"""
import sys
import zipfile
from pathlib import Path


def main():
    src, out = sys.argv[1], Path(sys.argv[2])
    with zipfile.ZipFile(src) as z:
        names = sorted(n for n in z.namelist() if n.endswith(".syx"))
        carts = [(Path(n).stem.replace("_", " "), z.read(n)) for n in names]
    for name, data in carts:
        if len(data) != 4104 or data[:2] != b"\xf0\x43":
            sys.exit(f"{name}: not a 32-voice DX7 bulk dump")
    lines = [f"/* Generated by tools/dexed_carts.py from {Path(src).name}. Do not edit. */",
             "#include <stdint.h>", "",
             f"const int om_dexed_banks = {len(carts)};",
             "const char *const om_dexed_bank_names[] = {" + ", ".join(f'"{n}"' for n, _ in carts) + "};",
             f"const uint8_t om_dexed_carts[{len(carts)}][32 * 128] = {{"]
    for _, data in carts:
        voices = data[6:6 + 32 * 128]
        lines.append("\t{" + ",".join(str(b) for b in voices) + "},")
    lines.append("};")
    out.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines) + "\n"
    if not out.exists() or out.read_text() != text:
        out.write_text(text)


if __name__ == "__main__":
    main()
